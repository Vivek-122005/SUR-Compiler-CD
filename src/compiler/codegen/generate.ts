// Phase 6 — Code generation.
// Turns the (optimized) IR into readable JavaScript that plays the tune through
// the Web Audio API — JavaScript is our target language the way x86 is for a C
// compiler. Also returns the note schedule used for the timeline.
//
// Safety: the generator only ever writes numbers and fixed text into the code.
// Swar names in comments come from the validated swar table, never from user input.

import type { CodegenOutput, IRInstr, PhaseResult, ScheduledEvent, Span } from '../types';
import { SWAR_NAMES, round, swarLabel } from '../swars';
import { foldValues } from '../optimizer/constant-fold';
import { expand } from '../ir/expand';
import { now, elapsed } from '../timing';

const safeLabel = (swar: string, octave: -1 | 0 | 1) =>
  SWAR_NAMES.includes(swar) ? swarLabel(swar, octave) : 'note';

const num = (x: number, digits: number) => {
  if (!Number.isFinite(x)) throw new Error(`non-finite number in IR: ${x}`);
  return x.toFixed(digits);
};

/**
 * Note ids: one per distinct source note, numbered in order of first appearance.
 * Unrolled copies share their original's id, so the editor can highlight the source.
 */
export function noteIds(ir: IRInstr[]): { idOf: (src: Span) => number; spans: Map<number, Span> } {
  const byOffset = new Map<number, number>();
  const spans = new Map<number, Span>();
  for (const ins of ir) {
    if (ins.op === 'PLAY' && !byOffset.has(ins.src.offset)) {
      const id = byOffset.size + 1;
      byOffset.set(ins.src.offset, id);
      spans.set(id, ins.src);
    }
  }
  return { idOf: (src) => byOffset.get(src.offset) ?? 0, spans };
}

/** The flat schedule: start time, length, frequency, label for every sound and silence. */
export function buildSchedule(ir: IRInstr[]): { schedule: ScheduledEvent[]; totalSeconds: number } {
  const events = expand(ir, { mergeRests: true });
  const schedule: ScheduledEvent[] = [];
  // Track time in beats per tempo so rounding never drifts (beats are multiples of 0.25).
  let elapsedSec = 0;
  for (const e of events) {
    const duration = round((e.beats * 60) / e.bpm, 6);
    const ev: ScheduledEvent = {
      start: round(elapsedSec, 6),
      duration,
      freq: e.freq,
      label: e.label,
    };
    if (e.src) ev.src = e.src;
    schedule.push(ev);
    elapsedSec += (e.beats * 60) / e.bpm;
  }
  return { schedule, totalSeconds: round(elapsedSec, 6) };
}

export function generate(input: IRInstr[]): PhaseResult<CodegenOutput> {
  const t0 = now();
  // If the optimizer was switched off, work out frequencies and seconds here,
  // using the same helper as the constant-folding pass.
  const ir = input.some(
    (i) =>
      (i.op === 'PLAY' && i.freq === undefined) || (i.op === 'REST' && i.seconds === undefined),
  )
    ? foldValues(input)
    : input;

  const { schedule, totalSeconds } = buildSchedule(ir);
  const ids = noteIds(ir);
  const notes = schedule.filter((e) => e.freq !== null).length;
  // count rests as written in the IR's expansion (before merging for display)
  const rests = expand(ir).filter((e) => e.freq === null).length;
  const tempo = ir.find((i) => i.op === 'TEMPO');
  const bpm = tempo?.op === 'TEMPO' ? tempo.bpm : 100;

  const lines: string[] = [
    '// Generated by the Sur compiler. Do not edit.',
    `// ${notes} notes, ${rests} rests, ${num(totalSeconds, 1)} seconds`,
  ];
  // TEMPO becomes a comment in the header
  lines.push(`// tempo ${bpm} bpm (1 beat = ${num(60 / bpm, 3)} s)`);
  lines.push(
    '',
    'let t = ctx.currentTime + 0.1;',
    '',
    'function note(freq, dur, id) {',
    '  const osc = ctx.createOscillator();',
    '  const gain = ctx.createGain();',
    "  osc.type = 'triangle';",
    '  osc.frequency.value = freq;',
    '  gain.gain.setValueAtTime(0, t);',
    '  gain.gain.linearRampToValueAtTime(0.3, t + 0.02); // soft attack',
    '  gain.gain.setValueAtTime(0.3, t + dur * 0.85);',
    '  gain.gain.linearRampToValueAtTime(0, t + dur * 0.95); // short gap between notes',
    '  osc.connect(gain).connect(out);',
    '  osc.start(t);',
    '  osc.stop(t + dur);',
    '  onNote(id, t);',
    '  t += dur;',
    '}',
    '',
    'function rest(dur) { t += dur; }',
    '',
  );

  let depth = 0;
  const pad = () => '  '.repeat(depth);
  for (const ins of ir) {
    switch (ins.op) {
      case 'TEMPO':
        break; // emitted in the header
      case 'PLAY':
        lines.push(
          `${pad()}note(${num(ins.freq!, 2)}, ${num(ins.seconds!, 3)}, ${ids.idOf(ins.src)}); // ${safeLabel(ins.swar, ins.octave)}`,
        );
        break;
      case 'REST':
        lines.push(`${pad()}rest(${num(ins.seconds!, 3)});`);
        break;
      case 'LOOP': {
        depth++;
        const i = `i${depth}`;
        lines.push(
          `${'  '.repeat(depth - 1)}for (let ${i} = 0; ${i} < ${Math.trunc(ins.count)}; ${i}++) {`,
        );
        break;
      }
      case 'ENDLOOP':
        depth--;
        lines.push(`${pad()}}`);
        break;
      case 'HALT':
        lines.push('return t;');
        break;
    }
  }

  return {
    phase: 'codegen',
    status: 'ok',
    output: { js: lines.join('\n') + '\n', schedule, totalSeconds },
    diagnostics: [],
    timeMs: elapsed(t0),
  };
}
